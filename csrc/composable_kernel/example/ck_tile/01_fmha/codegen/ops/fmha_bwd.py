@dataclass(frozen=True)
class FmhaBwdApiTrait:
    arch: ArchTrait
    idx: int  # this is not a tunable, but a counter to differentiate symbol
    # sync with fmha_bwd_traits<>, to generate fallback calls
    hdim: int
    dtype: str  # data type
    mode: str  # value from MODE_MAP
    tile: FmhaBwdDQDKDVTileSize
    mask: str
    bias: str
    dbias: str
    dropout: str
    spad1d: str  # spad for 1d kernels (dot/convert)
    dpad: Literal[0, 1, 8]
    dvpad: Literal[0, 1, 8]
    deterministic: str
    mask_impl: str
    tr_load: str

    @property
    def bm0(self) -> int:
        return self.tile.F_bm0

    @property
    def bn0(self) -> int:
        return self.tile.F_bn0

    @property
    def bhdq(self) -> int:
        return self.tile.F_bhdq

    @property
    def bhdv(self) -> int:
        return self.tile.F_bhdv

    @property
    def scheck(self) -> str:
        if self.mode == "group":
            return "true /*spad1d is always true in group mode*/"
        elif self.spad1d == "t":
            return f"true /*a.seqlen_q % {M0_1D} != 0*/"
        else:  # self.spad1d == "f"
            return f"a.seqlen_q % {M0_1D} == 0"

    @property
    def dcheck(self) -> str:
        if self.dpad == 0:
            return f"a.hdim_q % {self.bhdq} == 0"
        else:
            return f"a.hdim_q % {self.dpad} == 0"

    @property
    def dvcheck(self) -> str:
        if self.dvpad == 0:
            return f"a.hdim_v % {self.bhdv} == 0"
        else:
            return f"a.hdim_v % {self.dvpad} == 0"

    @property
    def max_seq_q_cond(self) -> str:
        if self.tile.max_seq_q != 0:
            return f" && (a.seqlen_q <= {self.tile.max_seq_q})"
        else:
            return ""

    @property
    def extra_cond(self) -> str:
        if self.tr_load == "t" and self.tile.max_seq_q == 0 and self.tile.F_bn0 == 128:
            return " && (a.seqlen_k <= 256)"
        else:
            return ""

    @property
    def convert_dq_bn0(self) -> int:
        return self.tile.F_bn0 if self.deterministic == "t" else 0

    @property
    def split_eligible(self) -> bool:
        return (
            self.tr_load == "f"
            and self.tile.max_seq_q == 0
            and self.dpad != 1
            and self.dvpad != 1
        )

    @property
    def qmajor_eligible(self) -> bool:
        return (
            self.split_eligible
            and self.arch.name == "gfx11"
            and self.dtype in ("fp16", "bf16")
            and (
                self.hdim == 64
                or (
                    os.getenv("CK_TILE_DEBUG_BWD_SPLIT_DQ_QMAJOR_D256", "0") == "1"
                    and self.hdim == 256
                )
            )
            and self.mode == "batch"
            and self.mask in ("no", "s_no")
            and self.bias == "no"
            and self.dbias == "f"
            and self.dropout == "no"
            and self.deterministic == "f"
            and self.tr_load == "f"
            and self.dpad == 0
            and self.dvpad == 0
            and self.tile.F_bhdq == self.hdim
            and self.tile.F_bhdv == self.hdim
        )

    @property
    def dot_do_o_kernel(self) -> FmhaBwdOGradDotOKernel:
        # TODO: we don't support tuning yet, so pick up one value for pad/occupancy
        #       support this in future
        def get_occupancy(dtype, hdim):
            return 2

        F_dvpad = "t" if self.dvpad else "f"
        return FmhaBwdOGradDotOKernel(
            F_arch=self.arch,
            F_idx=self.idx,
            F_hdim=self.hdim,
            F_dtype=self.dtype,
            F_bm0=M0_1D,
            F_spad=self.spad1d,
            F_dvpad=F_dvpad,
            F_mode=self.mode,
            F_occupancy=get_occupancy(self.dtype, self.hdim),
        )

    @property
    def dq_dk_dv_kernel(self) -> FmhaBwdDQDKDVKernel:
        return FmhaBwdDQDKDVKernel(
            F_arch=self.arch,
            F_idx=self.idx,
            F_hdim=self.hdim,
            F_dtype=self.dtype,
            F_tile=self.tile,
            F_dpad=self.dpad,
            F_dvpad=self.dvpad,
            F_bias=self.bias,
            F_dbias=self.dbias,
            F_dropout=self.dropout,
            F_mask=self.mask,
            F_mode=self.mode,
            F_deterministic=self.deterministic,
            mask_impl=self.mask_impl,
            F_trload=self.tr_load,
        )

    @property
    def convert_dq_kernel(self) -> FmhaBwdConvertQGradKernel:
        # TODO: we don't support tuning yet, so pick up one value for pad/occupancy
        #       support this in future
        def get_occupancy(dtype, hdim):
            return 2

        F_dpad = "t" if self.dpad else "f"
        return FmhaBwdConvertQGradKernel(
            F_arch=self.arch,
            F_idx=self.idx,
            F_hdim=self.hdim,
            F_dtype=self.dtype,
            F_bm0=M0_1D,
            F_bn0=self.convert_dq_bn0,
            F_spad=self.spad1d,
            F_dpad=F_dpad,
            F_mode=self.mode,
            F_occupancy=get_occupancy(self.dtype, self.hdim),
            F_deterministic=self.deterministic,
            disabled=self.tile.max_seq_q != 0,
        )


